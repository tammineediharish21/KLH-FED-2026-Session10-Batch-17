import java.io.*;

class Unaryoperator {
         public static void main(String[] args) {
           int a = 10;
           int b = 20;
         System.out.println("Postincrement : " +  ( a++) );
         System.out.println("Postincrement : " +  ( ++a) );

         System.out.println("Postincrement : " +  (b--) );
         System.out.println("Postincrement : " +  (--b) );
  }
}